using System.IO;
using TMPro;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// One-click FR-07 UI creation inside the selected ServiceCapacityPanel.
/// The output is real editable Unity UI, not a screenshot or UI mockup.
/// </summary>
public static class ServiceCapacityPanelBuilder
{
    private const string SpriteFolder = "Assets/FR07ServiceUI/Generated";
    private const string MenuPath = "Tools/FR-07/Build selected Service Capacity Panel";

    private static readonly Color Background = Hex("#142D31");
    private static readonly Color Row = Hex("#203C40");
    private static readonly Color TextWhite = Hex("#F6F5E7");
    private static readonly Color Muted = Hex("#A3C0B9");
    private static readonly Color Gold = Hex("#FFD789");
    private static readonly Color Services = Hex("#67D5B3");
    private static readonly Color Drinks = Hex("#66BEEB");
    private static readonly Color Food = Hex("#F3A96F");

    [MenuItem(MenuPath)]
    private static void Build()
    {
        GameObject selected = Selection.activeGameObject;
        if (selected == null || selected.name != "ServiceCapacityPanel" ||
            selected.GetComponent<RectTransform>() == null)
        {
            EditorUtility.DisplayDialog("FR-07", "Najprv v Hierarchy vyber objekt ServiceCapacityPanel pod Canvas.", "OK");
            return;
        }

        if (selected.transform.childCount > 0 && !EditorUtility.DisplayDialog(
                "FR-07: nahradiť obsah?",
                "Vybraný panel už má vnorené UI objekty. Prepísanie odstráni ich obsah. Pokračovať?",
                "Vytvoriť", "Zrušiť")) return;

        // Sprite is generated as an ordinary Unity asset; .meta will be generated by Unity.
        Sprite rounded = EnsureRoundedSprite();

        Undo.RegisterFullObjectHierarchyUndo(selected, "FR-07 Build Capacity Panel");
        while (selected.transform.childCount > 0)
            Undo.DestroyObjectImmediate(selected.transform.GetChild(0).gameObject);

        RectTransform root = selected.GetComponent<RectTransform>();
        root.anchorMin = root.anchorMax = new Vector2(1f, 1f);
        root.pivot = new Vector2(1f, 1f);
        root.anchoredPosition = new Vector2(-24f, -24f);
        root.sizeDelta = new Vector2(384f, 338f);
        root.localScale = Vector3.one;
        root.localRotation = Quaternion.identity;

        Image panelImage = selected.GetComponent<Image>();
        if (panelImage == null) panelImage = Undo.AddComponent<Image>(selected);
        panelImage.sprite = rounded;
        panelImage.type = Image.Type.Sliced;
        panelImage.color = Background;
        panelImage.raycastTarget = false;

        Shadow shadow = selected.GetComponent<Shadow>();
        if (shadow == null) shadow = Undo.AddComponent<Shadow>(selected);
        shadow.effectColor = new Color(0f, 0.07f, 0.08f, 0.6f);
        shadow.effectDistance = new Vector2(0f, -7f);
        shadow.useGraphicAlpha = true;

        // Decorative accent and editorial heading.
        Box("Accent", root, 23f, 19f, 34f, 4f, Gold, rounded);
        Label("Overline", root, "TROPICAL RESORT  /  OPERATIONS", 12, Muted,
              67f, 11f, 280f, 22f, TextAlignmentOptions.Left, FontStyles.Bold);
        Label("Heading", root, "SERVICE CAPACITY", 23, TextWhite,
              23f, 39f, 338f, 37f, TextAlignmentOptions.Left, FontStyles.Bold);

        // Delicate divider.
        Box("Divider", root, 23f, 84f, 338f, 1f, Hex("#426063"), null);

        ServiceCapacityPanel.Meter services = MeterRow(root, rounded, "Services", "SERVICES", "S", 100f, Services);
        ServiceCapacityPanel.Meter drinks = MeterRow(root, rounded, "Drinks", "DRINKS", "D", 169f, Drinks);
        ServiceCapacityPanel.Meter food = MeterRow(root, rounded, "Food", "FOOD", "J", 238f, Food);

        Box("StatusBadge", root, 24f, 312f, 73f, 17f, Hex("#36554B"), rounded);
        TextMeshProUGUI statusLabel = Label("Status", root, "DEMO", 10, Gold,
                  29f, 313f, 63f, 16f, TextAlignmentOptions.Center, FontStyles.Bold);
        TextMeshProUGUI waveLabel = Label("Wave", root, "NO ACTIVE WAVE", 11, Muted,
                  115f, 311f, 245f, 20f, TextAlignmentOptions.Right, FontStyles.Normal);

        ServiceCapacityPanel runtime = selected.GetComponent<ServiceCapacityPanel>();
        if (runtime == null) runtime = Undo.AddComponent<ServiceCapacityPanel>(selected);
        runtime.BindUI(services, drinks, food, statusLabel, waveLabel);

        EditorUtility.SetDirty(selected);
        EditorUtility.SetDirty(runtime);
        if (selected.scene.IsValid()) EditorSceneManager.MarkSceneDirty(selected.scene);
        Selection.activeGameObject = selected;

        EditorUtility.DisplayDialog("FR-07: panel pripravený",
            "UI panel bol vytvorený. V záložke Game ho uvidíš aj pred spustením hry. Hodnoty sú označené ako DEMO; na skutočné údaje ho neskôr napojíme cez SetUsage(...).", "OK");
    }

    private static ServiceCapacityPanel.Meter MeterRow(RectTransform parent, Sprite rounded,
                                                        string objectName, string heading,
                                                        string initial, float top, Color accent)
    {
        Image card = Box(objectName + "Card", parent, 19f, top, 346f, 61f, Row, rounded);
        RectTransform cardRoot = card.rectTransform;

        Box("InitialBackground", cardRoot, 14f, 12f, 35f, 35f, Hex("#355356"), rounded);
        Label("Initial", cardRoot, initial, 16, accent,
              14f, 13f, 35f, 34f, TextAlignmentOptions.Center, FontStyles.Bold);

        Label("Title", cardRoot, heading, 14, TextWhite,
              61f, 7f, 165f, 24f, TextAlignmentOptions.Left, FontStyles.Bold);
        TextMeshProUGUI count = Label("Value", cardRoot, "0 / 0", 14, Gold,
              252f, 7f, 80f, 24f, TextAlignmentOptions.Right, FontStyles.Bold);

        Image track = Box("ProgressTrack", cardRoot, 61f, 40f, 271f, 9f, Hex("#3B595A"), rounded);
        Image fill = Box("ProgressFill", track.rectTransform, 0f, 0f, 271f, 9f, accent, rounded);
        RectTransform fillRect = fill.rectTransform;
        fillRect.anchorMin = Vector2.zero;
        fillRect.anchorMax = Vector2.one;
        fillRect.offsetMin = Vector2.zero;
        fillRect.offsetMax = Vector2.zero;

        return new ServiceCapacityPanel.Meter
        {
            valueLabel = count,
            progressFill = fill
        };
    }

    private static Image Box(string name, Transform parent, float left, float top,
                             float width, float height, Color color, Sprite sprite)
    {
        GameObject go = NewUi(name, parent);
        SetRect((RectTransform)go.transform, left, top, width, height);
        Image image = go.AddComponent<Image>();
        image.color = color;
        image.raycastTarget = false;
        if (sprite != null)
        {
            image.sprite = sprite;
            image.type = Image.Type.Sliced;
        }
        return image;
    }

    private static TextMeshProUGUI Label(string name, Transform parent, string value,
                                        int fontSize, Color color,
                                        float left, float top, float width, float height,
                                        TextAlignmentOptions alignment, FontStyles style)
    {
        GameObject go = NewUi(name, parent);
        SetRect((RectTransform)go.transform, left, top, width, height);
        TextMeshProUGUI text = go.AddComponent<TextMeshProUGUI>();
        text.text = value;
        text.fontSize = fontSize;
        text.fontStyle = style;
        text.color = color;
        text.alignment = alignment;
        text.raycastTarget = false;
        text.enableAutoSizing = false;

        TMP_FontAsset font = AssetDatabase.LoadAssetAtPath<TMP_FontAsset>(
            "Assets/TextMesh Pro/Resources/Fonts & Materials/LiberationSans SDF.asset");
        if (font != null) text.font = font;
        return text;
    }

    private static GameObject NewUi(string name, Transform parent)
    {
        GameObject go = new GameObject(name, typeof(RectTransform));
        Undo.RegisterCreatedObjectUndo(go, "FR-07 Create UI");
        go.transform.SetParent(parent, false);
        return go;
    }

    private static void SetRect(RectTransform rect, float left, float top,
                                float width, float height)
    {
        rect.anchorMin = rect.anchorMax = new Vector2(0f, 1f);
        rect.pivot = new Vector2(0f, 1f);
        rect.anchoredPosition = new Vector2(left, -top);
        rect.sizeDelta = new Vector2(width, height);
    }

    private static Sprite EnsureRoundedSprite()
    {
        const string path = SpriteFolder + "/rounded_white.png";
        if (!AssetDatabase.IsValidFolder("Assets/FR07ServiceUI"))
            AssetDatabase.CreateFolder("Assets", "FR07ServiceUI");
        if (!AssetDatabase.IsValidFolder(SpriteFolder))
            AssetDatabase.CreateFolder("Assets/FR07ServiceUI", "Generated");

        if (!File.Exists(path))
        {
            const int size = 64;
            const float radius = 15f;
            Texture2D texture = new Texture2D(size, size, TextureFormat.RGBA32, false);
            Color[] pixels = new Color[size * size];
            Vector2 half = new Vector2(size / 2f, size / 2f);

            for (int y = 0; y < size; ++y)
            for (int x = 0; x < size; ++x)
            {
                Vector2 p = new Vector2(x + 0.5f - half.x, y + 0.5f - half.y);
                Vector2 q = new Vector2(Mathf.Abs(p.x), Mathf.Abs(p.y)) - half + new Vector2(radius, radius);
                float dist = Mathf.Min(Mathf.Max(q.x, q.y), 0f) +
                             new Vector2(Mathf.Max(q.x, 0f), Mathf.Max(q.y, 0f)).magnitude - radius;
                pixels[y * size + x] = new Color(1f, 1f, 1f, Mathf.Clamp01(0.5f - dist));
            }
            texture.SetPixels(pixels);
            texture.Apply();
            File.WriteAllBytes(path, texture.EncodeToPNG());
            Object.DestroyImmediate(texture);
        }

        AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceUpdate);
        TextureImporter importer = AssetImporter.GetAtPath(path) as TextureImporter;
        if (importer != null &&
            (importer.textureType != TextureImporterType.Sprite || importer.spriteBorder != new Vector4(15f, 15f, 15f, 15f)))
        {
            importer.textureType = TextureImporterType.Sprite;
            importer.spriteImportMode = SpriteImportMode.Single;
            importer.spriteBorder = new Vector4(15f, 15f, 15f, 15f);
            importer.alphaIsTransparency = true;
            importer.mipmapEnabled = false;
            importer.SaveAndReimport();
        }
        return AssetDatabase.LoadAssetAtPath<Sprite>(path);
    }

    private static Color Hex(string html)
    {
        ColorUtility.TryParseHtmlString(html, out Color result);
        return result;
    }
}
